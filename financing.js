const $ = id => document.getElementById(id);
const TERMS = [12, 24, 36, 48, 60, 72, 84];
const car = carFromQuery("car");
const startPrice = car ? car.price : Number(new URLSearchParams(location.search).get("price")) || 15000;

let calc = { payment: 0, months: 60 };
let lastOffer = null;

$("price").value = startPrice;

function buildTerms() {
  const selected = $("term").value || "60";
  $("term").replaceChildren(...TERMS.map(months => new Option(t("months")(months), months)));
  $("term").value = selected;
}

function renderForCar() {
  const box = $("forCar");
  if (!car) {
    box.hidden = true;
    return;
  }
  box.hidden = false;
  box.replaceChildren(`${t("forCar")}: `);
  const link = document.createElement("a");
  link.href = `car.html?id=${car.id}`;
  link.textContent = `${carName(car)} (${car.year})`;
  box.appendChild(link);
}

function calculate() {
  const price = Math.max(0, parseFloat($("price").value) || 0);
  const downPct = Number($("down").value);
  const rate = Number($("apr").value);
  const months = Number($("term").value);

  const downAmount = price * downPct / 100;
  const loan = price - downAmount;
  const payment = monthlyPayment(loan, rate, months);
  const total = payment * months;
  const interest = total - loan;

  $("downOut").textContent = `${downPct} % (${money(downAmount)})`;
  $("aprOut").textContent = `${rate.toLocaleString(localeByLanguage[currentLanguage], { minimumFractionDigits: 1, maximumFractionDigits: 1 })} %`;

  $("pay").innerHTML = `${money(payment, 2)} <small>${t("perMonthShort")}</small>`;
  $("loan").textContent = money(loan);
  $("interest").textContent = money(interest);
  $("total").textContent = money(total);

  const whole = downAmount + total;
  const share = value => (whole > 0 ? (value / whole) * 100 : 0) + "%";
  $("barDown").style.width = share(downAmount);
  $("barLoan").style.width = share(loan);
  $("barInterest").style.width = share(interest);

  calc = { payment, months };
}

function renderSuccess() {
  if (!lastOffer) return;
  $("successText").textContent = t("okText")(
    lastOffer.name, lastOffer.email, fmt(Math.round(lastOffer.payment)), lastOffer.months
  );
}

["price", "down", "term", "apr"].forEach(id => $(id).addEventListener("input", calculate));

$("offerForm").addEventListener("submit", event => {
  event.preventDefault();
  const form = event.currentTarget;
  if (!form.reportValidity()) return;

  const data = new FormData(form);
  /* DEMO: nothing is sent anywhere. Post `data` plus the numbers in `calc`
     (and the car id, if any) to your own backend here. */
  lastOffer = {
    name: data.get("name").trim(),
    email: data.get("email").trim(),
    payment: calc.payment,
    months: calc.months
  };
  renderSuccess();
  form.hidden = true;
  $("success").hidden = false;
});

initLanguage(() => {
  buildTerms();
  renderForCar();
  calculate();
  renderSuccess();
});
